
;	LSX-Dodgers DEF
;	MZ-2500 (2500モード / IPLブート)

MAC	EQU	4		;MZ-2500 (この値は本移植で決めた機種ID。BDOS 6Fh のL。MODE.COM等はこの値を「未知の機種」として何もせず終了する)
DEV	EQU	0

VER_6F	EQU	0011DH

RUN	EQU	04100H		;IPLヘッダ(レコード0, 256バイト)の直後
OFFSET	EQU	RUN-256
BDOS	EQU	0B006H	;TPAは0100H-B005H(約44KB)。バンク5(A000H-)にも本体が入るので、F:の窓はバンク1,3(M25MEM)
WORKAD	EQU	0F000H
TABLEAD	EQU	0EDD0H	;キー表5枚(112B x5=560B)が WORKAD(0F000H) 直前に収まる位置(AT_WORKの詰め物を無くして本体の空きを増やした)

;	初期値の要らない作業領域は、本体(B006H-DFFFH)の外の AT_TABLE..TABLEAD の詰め物の中(イメージに入らない)に置いて、本体の空きを増やす。
;	下から ENVBUF RFNAME OUTBUF HSLOTS の順に TABLEAD の直前まで。 INIT が0で埋める。 build.py が AT_TABLE <= BSSLOW を確かめる。
NSLOT		EQU	6		;同時に開けるファイル数
SLOTSZ		EQU	48
HSLOTS		EQU	TABLEAD-NSLOT*SLOTSZ
OUTBUF		EQU	HSLOTS-128
RFNAME		EQU	OUTBUF-64
ENVBUF		EQU	RFNAME-ENVSZ	;環境変数の表(起動時に0=空)
;	長いファイル名(M25LN.ASM): FN2(解析で拾った name2 10B) LNTAB(FCBの住所つきの記録 4枠x23B) LNNXT(次に上書きする枠のオフセット) LNTMP(作業4B)
LNSLOTS		EQU	4
LNSZ		EQU	23
LNBSS		EQU	ENVBUF-108
FN2		EQU	LNBSS
LNTAB		EQU	LNBSS+10
LNNXT		EQU	LNBSS+10+LNSLOTS*LNSZ
LNTMP		EQU	LNNXT+1
BSSLOW		EQU	LNBSS
KEYBF	EQU	0F300H
FATBF	EQU	0F330H
DTBUF	EQU	0A600H	;ディスクのデータバッファ(1KB)。カーネル時のバンク5の空き(A000H-B005H)に置く。元の FB30H はゲート用RAMに使う
KBUF	EQU	0FF30H
EDBUF	EQU	0A000H	;行編集(M25EDT)の履歴などのバッファ(1368B)。カーネル時のバンク5(ページ0Bh)の A000H-B005H は本体が使わない空き(TPAはユーザページ側)なので、そこに置く
TRAP38	EQU	0FFD9H
KJBASE	EQU	0A3D0H	;漢字表示(M25KJ.ASM)のコード。カーネル時のバンク5の空き(行編集バッファの後ろ〜LDVARS(A560H)の前)。INITがイメージから写す
KJLEAD	EQU	KJBASE	;PRINTから: 漢字の1バイト目か調べる(Z=取り込んだ)
KJTRAIL	EQU	KJBASE+3	;ESC2から: 2バイト目を受けて表示 / ESC k 0|1
KJCOLE	EQU	KJBASE+9	;CSI(SGR)から: 色 B(ANSI順0-7)を _COLORF へ
KJESC	EQU	KJBASE+6	;ESC1から: ESC k
#IF EXISTS COLS80
WIDTH	EQU	80		;80桁(IOCS TINITで切替)
#ELSE
WIDTH	EQU	40		;ブート時の40桁のまま使う
#ENDIF
LINE	EQU	25
COLORF	EQU	007H		;テキスト属性(白) bit2:G bit1:R bit0:B
KEYSP_H	EQU	20
KEYSP_L	EQU	131
COMS	EQU	15
MAX_SEC_SZ_H	EQU	4	;1セクタ1024バイトのサポート(2:off 4:on)
BUFFER	EQU	00100H

;	MZ-2500 ハードウェア
VRAM_PG	EQU	038H		;テキストVRAM/アトリビュート(MB38)
RAM7_PG	EQU	00FH		;バンク7(E000H-FFFFH)の通常ページ
ENVSZ	EQU	256	;環境変数の表の大きさ(M25ENV.ASM とオーバーレイの SET が使う)

;	---- ユーザ/カーネルのマップ切替(M25GATE) ----
;	カーネル(本体)のマップ: バンク5=KPG5, バンク6=KPG6。ユーザ(TPA)のマップ: バンク5=UPG5, バンク6=UPG6, バンク4=UPG4
KPG5	EQU	00BH
KPG6	EQU	006H
UPG4	EQU	00AH
UPG5	EQU	004H
UPG6	EQU	005H
TPATOP	EQU	0E000H		;TPAの上端(0006H の値)。0005H の JP の飛び先 UENTRY がここ
KSTK	EQU	0B000H		;カーネルのスタックの上端(カーネル時のバンク5の空き A000H-B005H の末尾)
STAGE	EQU	0AA00H		;COMローダのステージング(1KB。AA00H-ADFFH。スタックの下)
STAGEL	EQU	0400H
LDVARS	EQU	0A560H		;ローダの変数
;	共通バンク(バンク7)のゲート用RAM(旧 DTBUF の場所 FB30H-FF2FH。KBUF=FF30H の手前)
GVARS	EQU	0FB30H
GSTK	EQU	GVARS+040H	;GVARS+10H..3FH がゲートのスタック(48B)
UAFV	EQU	GVARS+0
UIFF	EQU	GVARS+1
UFN	EQU	GVARS+2
UACT	EQU	GVARS+3
UMORE	EQU	GVARS+4
INKRN	EQU	GVARS+5	;1=カーネルのマップで実行中 0=ユーザ
USP	EQU	GVARS+6
UBC	EQU	GVARS+8
UDE	EQU	GVARS+10
UHL	EQU	GVARS+12
UODE	EQU	GVARS+14
UOHL	EQU	GVARS+16
UDMA	EQU	GVARS+18
URAF	EQU	GVARS+20
URBC	EQU	GVARS+22
URDE	EQU	GVARS+24
URHL	EQU	GVARS+26
UCUR	EQU	GVARS+28
UTOT	EQU	GVARS+30
ULEN	EQU	GVARS+32
UCHK	EQU	GVARS+34
UDONE	EQU	GVARS+36
UDE0	EQU	GVARS+38
UTGT	EQU	GVARS+40
;	バウンスバッファ(GSTK の上)
BOUNCE	EQU	GVARS+040H	;DMA 128B
BOUNCEF	EQU	BOUNCE+080H	;FCB 40B
BOUNCEG	EQU	BOUNCEF+028H	;解析で出るFCB 40B
BOUNCES	EQU	BOUNCEG+028H	;文字列 128B
BOUNCEX	EQU	BOUNCES+080H	;行バッファ/ハンドル読み書き 260B
BOUNCEE	EQU	BOUNCEX+104H
IOCSOK	EQU	BOUNCEE		;1=IPL ROM のIOCSがある(起動時に判定) 0=なし
UIA	EQU	BOUNCEE+1	;ユーザの RST 18H(IOCS呼び出し)ゲートの一時置き場
UIIFF	EQU	BOUNCEE+2
UIHL	EQU	BOUNCEE+3
UIRET	EQU	BOUNCEE+5
UISP	EQU	BOUNCEE+7
UIRAF	EQU	BOUNCEE+9
UIRBC	EQU	BOUNCEE+11
UIRDE	EQU	BOUNCEE+13
UIRHL	EQU	BOUNCEE+15
UIDE	EQU	BOUNCEE+17
IOCTN	EQU	0A0H		;IOCT の関数数(関数番号 0..9FH)
BOOTDEV	EQU	0FF20H		;ブートローダが入れる起動デバイス(1=HDD)。INITが読む
IOCT	EQU	BOUNCEE+19	;RST 18H の振り分け表(関数番号*2。DW: 0000=未実装 0001=ROMのIOCSへ素通し その他=自前ハンドラ。末尾 FF2FH の手前に収まる)
