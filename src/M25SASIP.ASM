;	SASI基板の検出とパーティション表の探索(INITとHDDブートローダで共用。SASRD/SASBASE を使う)
SASPROBE:
	LD	A,3			;HDDのスピンアップ待ち: バスリセット+表の読みをBSY=1の間だけ最大3回待って再試行
	LD	(SASTRY),A
SASP00:
	LD	A,008H
	OUT	(0A5H),A		;SASIバスリセット(RST)
	LD	B,0
SASP0:	DJNZ	SASP0
	XOR	A
	OUT	(0A5H),A
	LD	B,0
SASP1:	DJNZ	SASP1
	IN	A,(0A5H)
	CP	0FFH
	JR	Z,SASPNO		;FFh = SASI基板なし
	AND	020H
	JR	NZ,SASPRT		;BSY=1: まだ使えない -> 待って再試行
	LD	A,3
	LD	(SASBASE),A
	XOR	A
	LD	(SASBASE+1),A
	LD	(SASBASE+2),A		;ブロック3 = パーティション表
	LD	B,1
	LD	C,0
	LD	DE,0
	LD	HL,04000H
	CALL	SASRD
	JR	NC,SASP6
	JR	SASPNO			;選択に応答なし(HDD無し): 待たずに終了(起動を遅らせない)
SASPRT:
	LD	BC,0
SASPW:	DEC	BC			;約0.3秒待つ
	LD	A,B
	OR	C
	JR	NZ,SASPW
	LD	A,(SASTRY)
	DEC	A
	LD	(SASTRY),A
	JR	NZ,SASP00
	JR	SASPNO
SASP6:
	LD	HL,04000H
	LD	DE,SASSIG
	LD	B,7
SASP2:	LD	A,(DE)
	CP	(HL)
	JR	NZ,SASPNO		;"EHSASI " でない
	INC	HL
	INC	DE
	DJNZ	SASP2
	LD	IX,04010H
	LD	B,15
SASP3:	LD	A,(IX+3)		;SASI-ID(0=未使用エントリ)
	OR	A
	JR	Z,SASP4
	LD	A,(IX+4)
	OR	A
	JR	NZ,SASP4		;LUN0のみ
	BIT	7,(IX+0)
	JR	NZ,SASP5		;優先起動
SASP4:	LD	DE,16
	ADD	IX,DE
	DJNZ	SASP3
SASPNO:
	SCF
	RET
SASP5:	LD	A,(IX+7)
	LD	(SASBASE),A
	LD	A,(IX+6)
	LD	(SASBASE+1),A
	LD	A,(IX+5)
	AND	01FH
	LD	(SASBASE+2),A
	AND	A
	RET
SASTRY:	DB	0
SASSIG:	DEFM	"EHSASI "
